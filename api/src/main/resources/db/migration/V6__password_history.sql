-- ============================================================
-- 密码历史(架构文档 7.1.2):禁止重复使用最近若干次用过的密码
--
-- 背景:用户被要求改密时,最常见的应对是"在原密码后面加个 1",那样改密只是走个流程,
-- 初始密码泄露这类风险并没有被消除。所以要能比对"最近用过哪些密码"。
--
-- 只存哈希(与密码同一套 bcrypt),不存明文 —— 存明文等于把"记住密码"的收益拱手让人。
-- 存法是逗号分隔的一列(最近一次在最前),最多保留 minimall.login.password-history-count 个,
-- 够用且不需要额外的表与关联。
--
-- 同表的 pwd_update_time 列早就有(用途注释写的是"最近一次改密时间"),但此前从未被读取;
-- 本次一并启用:密码有效期靠它判断(见 minimall.login.password-expire-days)。
-- ============================================================

ALTER TABLE sys_user
    ADD COLUMN password_history VARCHAR(512) NULL COMMENT '最近若干次密码哈希(逗号分隔,最近一次在最前),用于禁止重复使用' AFTER pwd_update_time;
